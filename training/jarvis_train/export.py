"""Merge the trained adapter and register it with Ollama.

A fine-tune that never reaches the running application is theatre, so this is
part of the pipeline rather than a manual afterthought.

The merge deliberately loads the base model in **fp16 on CPU**, not in the 4-bit
form training used. Merging LoRA deltas into dequantised 4-bit weights bakes the
quantisation error permanently into the result and then quantises it a second
time on the way into Ollama. Loading fp16 costs RAM and some patience, and keeps
one lossy step instead of two.

Ollama imports a safetensors directory directly and quantises on the way in, so
llama.cpp is not needed here. The quantisation *names* are Ollama's own and are
not the llama.cpp ones: measured against the installed ollama 0.40.16,
``-q q4_K_M`` is rejected with "supported types are int4, int8, nvfp4, mxfp4,
mxfp8". Hence the ``int4`` default. Pass ``--quantize`` if a future version
renames them again.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path

from jarvis_train import contract

OUT_DIR = Path(__file__).resolve().parents[1] / "out"


MODELFILE = """# Generated by training/jarvis_train/export.py -- do not edit by hand.
#
# The SYSTEM block is the distilled prompt the adapter was trained against.
# It is a default: an explicit system message in an /api/chat request still
# overrides it, which is what the backend sends.
FROM {model_dir}

PARAMETER temperature 0.1
PARAMETER top_p 0.9
PARAMETER num_ctx 8192
PARAMETER stop "<|im_end|>"

SYSTEM \"\"\"{system}\"\"\"
"""


def merge(base_model: str, adapter: Path, destination: Path) -> None:
    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    print(f"loading base in fp16 on CPU: {base_model}")
    model = AutoModelForCausalLM.from_pretrained(
        base_model, dtype=torch.float16, device_map="cpu"
    )
    print(f"applying adapter: {adapter}")
    model = PeftModel.from_pretrained(model, str(adapter), device_map="cpu")
    print("merging LoRA weights into the base")
    model = model.merge_and_unload()

    destination.mkdir(parents=True, exist_ok=True)
    print(f"writing merged model to {destination}")
    model.save_pretrained(str(destination), safe_serialization=True)

    tokenizer_source = adapter if (adapter / "tokenizer_config.json").exists() else base_model
    AutoTokenizer.from_pretrained(str(tokenizer_source)).save_pretrained(str(destination))
    print("merge complete")


def write_modelfile(model_dir: Path, path: Path) -> None:
    """Write the Modelfile. `model_dir` is the merged safetensors directory or,
    on Ollama versions that reject it, a converted .gguf file -- `FROM` accepts
    either."""
    # Ollama resolves a relative FROM against the Modelfile's directory.
    text = MODELFILE.format(
        model_dir=model_dir.resolve().as_posix(),
        system=contract.TUNED_SYSTEM_PROMPT,
    )
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path}")


def ollama_create(name: str, modelfile: Path, quantize: str) -> bool:
    command = ["ollama", "create", name, "-f", str(modelfile)]
    if quantize:
        command += ["-q", quantize]
    print(f"running: {' '.join(command)}")
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=3600)
    except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
        print(f"ollama create failed to run: {exc}")
        return False
    print(result.stdout[-3000:])
    if result.returncode != 0:
        print(f"ollama create exited {result.returncode}")
        print(result.stderr[-3000:])
        return False
    print(f"registered Ollama model: {name}")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description="Merge adapter and register with Ollama.")
    parser.add_argument("--adapter", type=Path, default=OUT_DIR / "adapter")
    parser.add_argument("--base-model", default=None,
                        help="defaults to the base recorded in training_meta.json")
    parser.add_argument("--merged", type=Path, default=OUT_DIR / "merged")
    # Ollama 0.40.16 cannot import a Qwen2 safetensors directory at all -- its
    # safetensors path only accepts MLX architectures, and `ADAPTER` (applying
    # the LoRA at runtime) was removed outright. A GGUF built from the merge is
    # the only route in. Produce one with llama.cpp's convert_hf_to_gguf.py:
    #   python convert_hf_to_gguf.py out/merged --outtype f16     #       --outfile out/gguf/<name>-f16.gguf
    # then pass it here. See RESULTS.md, "Deployment is blocked on the Ollama
    # import", for the exact errors.
    parser.add_argument("--from-gguf", type=Path, default=None,
                        help="import this GGUF instead of the safetensors merge")
    parser.add_argument("--name", default="jarvis-router")
    # Ollama's own names, not llama.cpp's: "q4_K_M" is rejected by ollama
    # 0.40.16. Verified supported: int4, int8, nvfp4, mxfp4, mxfp8.
    parser.add_argument("--quantize", default="int4")
    parser.add_argument("--skip-merge", action="store_true")
    parser.add_argument("--skip-ollama", action="store_true")
    parser.add_argument("--prune-merged", action="store_true",
                        help="delete the fp16 merge after Ollama has imported it")
    args = parser.parse_args()

    base = args.base_model
    meta_path = args.adapter / "training_meta.json"
    if base is None:
        if not meta_path.exists():
            raise SystemExit(f"no --base-model given and {meta_path} is missing")
        base = json.loads(meta_path.read_text(encoding="utf-8"))["base_model"]
    print(f"base model: {base}")

    if not args.skip_merge:
        merge(base, args.adapter, args.merged)

    source = args.from_gguf if args.from_gguf is not None else args.merged
    if args.from_gguf is not None and not args.from_gguf.exists():
        raise SystemExit(f"--from-gguf {args.from_gguf} does not exist")
    modelfile = args.merged.parent / f"Modelfile.{args.name}"
    write_modelfile(source, modelfile)

    created = False
    if not args.skip_ollama:
        created = ollama_create(args.name, modelfile, args.quantize)

    if args.prune_merged and created:
        print(f"removing the fp16 merge at {args.merged}")
        shutil.rmtree(args.merged, ignore_errors=True)

    # Do not print next steps after a failure. The first run of this script
    # printed "next: ollama run ..." even though `ollama create` had exited 1,
    # which reads as a successful export of a model that does not exist.
    if not args.skip_ollama and not created:
        raise SystemExit(
            f"ollama create failed, so '{args.name}' was not registered. The merged "
            f"fp16 model is still at {args.merged}; fix the error above and re-run "
            f"with --skip-merge to retry the import without merging again."
        )

    print("\nnext:")
    print(f"  ollama run {args.name}")
    print(f"  set JARVIS_LOCAL_LLM_MODEL={args.name} and "
          f"JARVIS_LOCAL_LLM_PROMPT_PROFILE=tuned in backend/.env")


if __name__ == "__main__":
    main()
