"""Utterance templates and label builders for every tool in the registry.

Each ``Intent`` pairs the way a person actually says something out loud with the
exact JSON the server expects back. Phrasings are written for *voice* input, not
typing: lowercase, unpunctuated, hesitant, sometimes with the wake word still
glued to the front, because that is what faster-whisper hands the backend.

Target formats are not improvised. Each one is quoted from the production system
prompt in ``backend/app/services/anthropic_reasoning.py`` and cross-checked
against the real dispatcher in ``backend/app/api/tools.py``:

* ``control_home_device`` -> ``"<entity_id> on"`` / ``"<entity_id> off"``
  (``tools.py`` does ``target.rpartition(" ")``)
* ``open_website``        -> ``"<site_key>"`` or ``"<site_key> <search terms>"``
  (``tools.py`` does ``target.partition(" ")``)
* ``close_website``       -> ``"<site_key>"``
* ``move_file``           -> ``"<source> to <destination>"``
* ``write_file``/``append_file`` -> path in ``target``, body in ``content``
* ``take_screenshot``     -> the user's question verbatim, or empty
* ``get_current_time``, ``get_pc_status``, ``list_open_windows``,
  ``delete_all_memories`` -> no target

``requires_confirmation`` is never written by hand: it is read from the registry
dataclass, which derives it from the risk tier.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable, Dict, List, Mapping, Optional

Slots = Mapping[str, str]


@dataclass
class Intent:
    """One user goal: how it gets said, and what the model must emit."""

    name: str
    tool: Optional[str]
    templates: List[str]
    answers: List[str]
    slots: Dict[str, List[str]] = field(default_factory=dict)
    # Phrasings used ONLY to evaluate, never to train, and deliberately
    # written to be oblique -- indirect requests, statements of need, odd word
    # order. These exist because the index-based holdout cannot stay a clean
    # generalisation test forever: whenever coverage of a phrasing family is
    # widened (as it was for plural "lights"), a previously-hard held-out
    # template becomes a near-duplicate of something in training, and the
    # holdout score quietly turns into a coverage score. These phrasings are
    # not in `templates`, so no amount of template expansion can leak them,
    # and test_dataset_contract asserts that.
    adversarial: List[str] = field(default_factory=list)
    target: Callable[[Slots], str] = lambda s: ""
    content: Callable[[Slots], str] = lambda s: ""
    # Tools that must be present in available_tools for this intent to be
    # proposable. Defaults to [tool].
    needs: Optional[List[str]] = None

    def required_tools(self) -> List[str]:
        if self.needs is not None:
            return self.needs
        return [self.tool] if self.tool else []


